import { runAgentFactory } from "../src/core/agent-factory.ts";
import { applyBehavioralPolicy, reviewResponse } from "../src/core/behavioral-engine.ts";

function lexicalCoverage(reference, answer) {
  const terms = new Set(String(reference).toLocaleLowerCase().match(/[\\p{L}\\p{N}]{3,}/gu) || []);
  const output = new Set(String(answer).toLocaleLowerCase().match(/[\\p{L}\\p{N}]{3,}/gu) || []);
  if (!terms.size) return null;
  return Number(([...terms].filter(term => output.has(term)).length / terms.size).toFixed(4));
}

async function complete(engine, prompt) {
  const result = await engine.chat.completions.create({
    messages: [
      { role: "system", content: "Answer in the user's language. Use only the supplied course context, state uncertainty, and do not invent facts." },
      { role: "user", content: prompt }
    ],
    temperature: 0.2,
    max_tokens: 384,
    stream: false
  });
  const content = result?.choices?.[0]?.message?.content;
  if (typeof content !== "string" || !content.trim()) throw new Error("LOCAL_MODEL_EMPTY_RESPONSE");
  return content.trim();
}

export async function runLocalModelComparison({ engine, modelId, prompt, reference = "" }) {
  if (!engine || typeof engine.chat?.completions?.create !== "function") throw new Error("LOCAL_MODEL_NOT_READY");
  if (typeof modelId !== "string" || !/^Qwen/i.test(modelId)) throw new Error("SELECT_A_QWEN_MODEL");
  if (typeof prompt !== "string" || !prompt.trim() || prompt.length > 12000) throw new Error("BENCHMARK_PROMPT_INVALID");

  const rawStart = performance.now();
  const rawOutput = await complete(engine, prompt);
  const rawLatencyMs = Number((performance.now() - rawStart).toFixed(2));

  const pipelineStart = performance.now();
  const pipeline = await runAgentFactory({
    id: "p4-local-qwen-benchmark",
    objective: "Generate a support-grounded academic answer and review it before returning it",
    domain: "school",
    depth: 0,
    constraints: ["local_webllm_only", "no_cloud_inference", "estimated_spend=0 EUR", "same_prompt_as_raw_baseline"]
  }, {
    decompose: () => [],
    execute: async ({ signal }) => {
      if (signal.aborted) throw new Error("LOCAL_PIPELINE_ABORTED");
      const content = await complete(engine, prompt);
      if (signal.aborted) throw new Error("LOCAL_PIPELINE_ABORTED");
      return { agentId: "QwenLocalWebLLM", content, evidence: [{ claim: "Output generated by the already-loaded local WebLLM engine", status: "OBSERVED", source: modelId }] };
    },
    saboteur: (_task, output) => {
      const review = reviewResponse(output.content, "academic");
      return { passed: review.accepted, findings: review.issues };
    },
    synthesize: (_task, accepted) => {
      const reviewed = applyBehavioralPolicy(accepted[0]?.content || "", "academic");
      if (!reviewed.accepted) throw new Error("BEHAVIORAL_ENGINE_REJECTED_OUTPUT");
      return reviewed.text;
    },
    timeoutMs: 60000
  });
  const pipelineLatencyMs = Number((performance.now() - pipelineStart).toFixed(2));

  return {
    schema: "jx.p4.local-qwen-comparison.v1",
    mode: "REAL_LOCAL_WEBLLM",
    inferenceRoute: "BROWSER_WEBGPU_LOCAL",
    modelId,
    modelCalls: 2,
    cloudInferenceCalls: 0,
    rawQwen: { status: "REAL_LOCAL_MODEL_OUTPUT", output: rawOutput, latencyMs: rawLatencyMs, lexicalCoverage: lexicalCoverage(reference, rawOutput) },
    pipeline: {
      status: pipeline.status,
      output: pipeline.output,
      latencyMs: pipelineLatencyMs,
      agentFactory: "EXECUTED",
      saboteur: pipeline.status === "VALIDATED" ? "PASSED" : pipeline.status,
      behavioralEngine: "EXECUTED",
      findings: pipeline.findings
    },
    estimatedSpendEUR: 0,
    limitations: ["Lexical coverage is not a correctness or hallucination score.", "Two sequential generations use the same already-loaded local model and prompt.", "Model download is a separate user-initiated setup step; this benchmark does not download or initialize models."]
  };
}
